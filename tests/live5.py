from livelib import *
async def typ(pg, sel): return await pg.eval_on_selector(sel, 'e => e.type')
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        store = mock.Store()
        # ---------- show / hide on the sign-in page ----------
        ctx, pg = await phone(b, store)
        await pg.goto(URL); await pg.wait_for_selector('#gSignin:not([hidden])')
        check('password starts hidden', await typ(pg, '#siPass') == 'password')
        await pg.fill('#siPass', 'correct-horse-1')
        btn = pg.locator('[data-showpw="siPass"]')
        check('button says Show password', (await btn.inner_text()) == 'Show password')
        await btn.click()
        check('click reveals what was typed', await typ(pg, '#siPass') == 'text' and await pg.input_value('#siPass') == 'correct-horse-1')
        check('button now says Hide password', (await btn.inner_text()) == 'Hide password')
        await btn.click()
        check('click hides it again', await typ(pg, '#siPass') == 'password' and (await btn.inner_text()) == 'Show password')
        check('button is a big enough tap target', (await btn.evaluate('e => e.getBoundingClientRect().height')) >= 44)
        await pg.screenshot(path='pw-signin.png')
        # revealed, then signed in, then signed out: the next person to arrive sees it hidden
        await btn.click(); await pg.fill('#siEmail', 'eloise@example.test'); await pg.click('#siGo')
        await pg.wait_for_selector('#appMain:not([hidden])')
        await pg.evaluate('window.scrollTo(0, 99999)'); await pg.click('#btnSignOut'); await pg.click('#dlgBtns button:text-is("Sign out")')
        await pg.wait_for_selector('#gSignin:not([hidden])')
        check('after signing out the box is hidden again', await typ(pg, '#siPass') == 'password' and (await btn.inner_text()) == 'Show password' and await pg.input_value('#siPass') == '')

        # ---------- change password, signed in ----------
        await pg.fill('#siEmail', 'eloise@example.test'); await pg.fill('#siPass', 'correct-horse-1'); await pg.click('#siGo')
        await pg.wait_for_selector('#appMain:not([hidden])')
        await pg.evaluate('window.scrollTo(0, 99999)')
        check('footer has Change password', await pg.is_visible('#btnPassword'))
        await pg.click('#btnPassword')
        check('dialog opens with both boxes hidden', await pg.is_visible('#pwDlg') and await typ(pg, '#cpPass') == 'password' and await typ(pg, '#cpPass2') == 'password')
        await pg.fill('#cpPass', 'short'); await pg.fill('#cpPass2', 'short'); await pg.click('#cpGo')
        check('too short is refused', '10 characters' in await pg.inner_text('#cpMsg'))
        await pg.fill('#cpPass', 'a-brand-new-one-1'); await pg.fill('#cpPass2', 'a-brand-new-one-2'); await pg.click('#cpGo')
        check('mismatch is refused', "don't match" in await pg.inner_text('#cpMsg'))
        await pg.fill('#cpPass', 'aaaaaaaaaa'); await pg.fill('#cpPass2', 'aaaaaaaaaa'); await pg.click('#cpGo')
        await until(pg, "document.querySelector('#cpMsg').textContent.includes('easy to guess')")
        check('an easy-to-guess one gets a plain explanation, dialog stays open', await pg.is_visible('#pwDlg'))
        check('nothing changed for the refused ones', store.users['eloise@example.test'] == 'correct-horse-1')
        await pg.fill('#cpPass', 'a-brand-new-one-1'); await pg.fill('#cpPass2', 'a-brand-new-one-1')
        await pg.locator('[data-showpw="cpPass,cpPass2"]').click()
        check('one button shows both boxes', await typ(pg, '#cpPass') == 'text' and await typ(pg, '#cpPass2') == 'text')
        await pg.screenshot(path='pw-dialog.png')
        await pg.click('#cpGo'); await pg.wait_for_selector('#pwDlg', state='hidden')
        check('success closes the dialog and says so', 'Password changed' in await pg.inner_text('#toast'))
        check('the database was given the new password', store.users['eloise@example.test'] == 'a-brand-new-one-1')
        await pg.click('#btnPassword')
        check('reopening starts empty and hidden', await pg.input_value('#cpPass') == '' and await typ(pg, '#cpPass') == 'password')
        await pg.fill('#cpPass', 'typed but not saved'); await pg.click('#cpCancel')
        await pg.click('#btnPassword')
        check('cancel throws away what was typed', await pg.input_value('#cpPass') == '')
        await pg.keyboard.press('Escape')
        check('still signed in and the planner is intact', await pg.is_visible('#appMain'))
        # sign out, old password refused, new one works
        await pg.click('#btnSignOut'); await pg.click('#dlgBtns button:text-is("Sign out")'); await pg.wait_for_selector('#gSignin:not([hidden])')
        await pg.fill('#siEmail', 'eloise@example.test'); await pg.fill('#siPass', 'correct-horse-1'); await pg.click('#siGo')
        await until(pg, "document.querySelector('#siMsg').textContent.length > 0")
        check('the old password no longer works', "isn't right" in await pg.inner_text('#siMsg'))
        await pg.fill('#siPass', 'a-brand-new-one-1'); await pg.click('#siGo'); await pg.wait_for_selector('#appMain:not([hidden])')
        check('the new password works', True)

        # ---------- set-password page (invite or reset link) has the same toggle ----------
        sess, _ = store.issue('toby@example.test')
        ctx2, pg2 = await phone(b, store)
        await pg2.goto(URL + '#access_token=%s&expires_in=3600&refresh_token=%s&token_type=bearer&type=invite' % (sess['access_token'], sess['refresh_token']))
        await pg2.wait_for_selector('#gSetpw:not([hidden])')
        await pg2.fill('#spPass', 'seen-before-saving'); await pg2.fill('#spPass2', 'seen-before-saving')
        await pg2.locator('[data-showpw="spPass,spPass2"]').click()
        check('set-password page: one button shows both boxes', await typ(pg2, '#spPass') == 'text' and await typ(pg2, '#spPass2') == 'text')

        # ---------- demo mode is untouched ----------
        ctx3, pg3 = await phone(b, store)
        await pg3.goto(URL + '?demo=1'); await pg3.wait_for_selector('#appMain:not([hidden])')
        check('demo mode: no footer, so no password or sign-out buttons', not await pg3.is_visible('#foot'))
        check('no page errors', not pg.errs and not pg2.errs and not pg3.errs, pg.errs + pg2.errs + pg3.errs)
        check('nothing blocked by the security policy', not pg.csp and not pg2.csp and not pg3.csp, pg.csp)
        print('\nFAILED:', bad or 'none')
        await b.close()
asyncio.run(main())
